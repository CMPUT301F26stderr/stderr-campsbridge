/**
 * Independent stored document and corresponding application value.
 *
 * @param T Model type represented by the document.
 * @param path Literal stored identity, deliberately independent of path-building helpers.
 * @param codec Production codec under test.
 * @param fields Handwritten schema fields; never generated by the production encoder.
 * @param value Expected application value.
 */
data class DocumentFixture<T>(
    val path: String,
    val codec: DocumentCodec<T>,
    val fields: Map<String, Any?>,
    val value: T,
) {
    /** Gives parameterized failures a readable document identity. */
    override fun toString(): String =
        path
}

